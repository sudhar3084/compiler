"""
parser.py — Recursive-Descent Syntax Analyzer for CompilerX.

Parses the token stream generated by Lexer into an Abstract Syntax Tree (AST).
Supports variable declarations, assignments, compound assignments, arithmetic and
boolean expressions with full operator precedence, if/else-if/else branches,
while loops, blocks, and print() statements. Includes panic-mode synchronization
to report clear, non-cascading syntax errors with exact line and column numbers.
"""

from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Tuple

from ast_nodes import (
    ASTNode,
    Assignment,
    BinaryOp,
    Block,
    Identifier,
    IfStmt,
    Literal,
    PrintStmt,
    Program,
    UnaryOp,
    VarDecl,
    WhileStmt,
)
from lexer import Token, TokenType


@dataclass
class SyntaxErrorDetail:
    """Represents a syntax error with line and column metadata."""
    message: str
    line: int
    column: int
    found_token: str = ""

    def format(self) -> str:
        return f"[Syntax Error] Line {self.line}, Col {self.column}: {self.message}"

    def to_dict(self) -> Dict[str, Any]:
        return {
            "Phase": "Syntax Analysis",
            "Line": self.line,
            "Column": self.column,
            "Near Token": self.found_token,
            "Message": self.message,
        }


class _ParseAbortError(Exception):
    """Internal exception raised to unwind the current statement during panic-mode recovery."""
    pass


class Parser:
    """Recursive-descent parser for the CompilerX language."""

    TYPE_TOKENS = {
        TokenType.INT_KW: "int",
        TokenType.FLOAT_KW: "float",
        TokenType.BOOL_KW: "bool",
        TokenType.STRING_KW: "string",
    }

    def __init__(self, tokens: List[Token]):
        self.tokens = tokens
        self.pos = 0
        self.errors: List[SyntaxErrorDetail] = []

    def _current(self) -> Token:
        if self.pos >= len(self.tokens):
            return self.tokens[-1]
        return self.tokens[self.pos]

    def _peek(self, offset: int = 1) -> Token:
        idx = self.pos + offset
        if idx >= len(self.tokens):
            return self.tokens[-1]
        return self.tokens[idx]

    def _is_at_end(self) -> bool:
        return self._current().type == TokenType.EOF

    def _advance(self) -> Token:
        tok = self._current()
        if not self._is_at_end():
            self.pos += 1
        return tok

    def _check(self, token_type: TokenType) -> bool:
        return self._current().type == token_type

    def _match(self, *types: TokenType) -> Optional[Token]:
        for t in types:
            if self._check(t):
                return self._advance()
        return None

    def _expect(self, token_type: TokenType, message: str) -> Token:
        if self._check(token_type):
            return self._advance()
        cur = self._current()
        found_desc = f"'{cur.value}'" if cur.type != TokenType.EOF else "end of file"
        full_msg = f"{message} (found {found_desc})"
        self.errors.append(
            SyntaxErrorDetail(
                message=full_msg,
                line=cur.line,
                column=cur.column,
                found_token=str(cur.value),
            )
        )
        raise _ParseAbortError()

    def _synchronize(self) -> None:
        """Panic-mode error recovery: advance until a statement boundary."""
        self._advance()
        while not self._is_at_end():
            if self.pos > 0 and self.tokens[self.pos - 1].type == TokenType.SEMICOLON:
                return
            if self._current().type in (
                TokenType.INT_KW,
                TokenType.FLOAT_KW,
                TokenType.BOOL_KW,
                TokenType.STRING_KW,
                TokenType.IF,
                TokenType.WHILE,
                TokenType.PRINT,
                TokenType.RBRACE,
            ):
                return
            self._advance()

    def parse(self) -> Tuple[Program, List[SyntaxErrorDetail]]:
        """Parses the token stream into a Program AST node and a list of syntax errors."""
        statements: List[ASTNode] = []
        start_tok = self._current()

        while not self._is_at_end():
            try:
                stmt = self._parse_statement()
                if stmt is not None:
                    statements.append(stmt)
            except _ParseAbortError:
                self._synchronize()

        return Program(line=start_tok.line, column=start_tok.column, statements=statements), self.errors

    def _parse_statement(self) -> Optional[ASTNode]:
        cur = self._current()

        # 1. Variable Declaration
        if cur.type in self.TYPE_TOKENS:
            return self._parse_var_decl()

        # 2. If Statement
        if cur.type == TokenType.IF:
            return self._parse_if_stmt()

        # 3. While Statement
        if cur.type == TokenType.WHILE:
            return self._parse_while_stmt()

        # 4. Print Statement
        if cur.type == TokenType.PRINT:
            return self._parse_print_stmt()

        # 5. Block Statement `{ ... }`
        if cur.type == TokenType.LBRACE:
            return self._parse_block()

        # 6. Assignment Statement `identifier = expr;`
        if cur.type == TokenType.IDENTIFIER:
            return self._parse_assignment_stmt()

        # 7. Empty semicolon `;`
        if cur.type == TokenType.SEMICOLON:
            self._advance()
            return None

        # Unexpected token at start of statement
        self.errors.append(
            SyntaxErrorDetail(
                message=f"Unexpected token '{cur.value}' at start of statement",
                line=cur.line,
                column=cur.column,
                found_token=str(cur.value),
            )
        )
        raise _ParseAbortError()

    def _parse_var_decl(self) -> VarDecl:
        type_tok = self._advance()
        var_type = self.TYPE_TOKENS[type_tok.type]
        id_tok = self._expect(
            TokenType.IDENTIFIER,
            f"Expected variable name after type '{var_type}'",
        )
        initializer: Optional[ASTNode] = None
        if self._match(TokenType.ASSIGN):
            initializer = self._parse_expression()

        self._expect(
            TokenType.SEMICOLON,
            f"Expected ';' after variable declaration of '{id_tok.value}'",
        )
        return VarDecl(
            line=type_tok.line,
            column=type_tok.column,
            var_type=var_type,
            name=str(id_tok.value),
            initializer=initializer,
        )

    def _parse_assignment_stmt(self) -> Assignment:
        id_tok = self._advance()
        var_name = str(id_tok.value)

        # Standard assignment `x = expr;`
        if self._match(TokenType.ASSIGN):
            expr = self._parse_expression()
            self._expect(
                TokenType.SEMICOLON,
                f"Expected ';' after assignment to '{var_name}'",
            )
            return Assignment(
                line=id_tok.line,
                column=id_tok.column,
                name=var_name,
                value=expr,
            )

        # Compound assignment (`+=`, `-=`, `*=`, `/=`) desugared to `x = x op expr;`
        compound_map = {
            TokenType.PLUS_ASSIGN: "+",
            TokenType.MINUS_ASSIGN: "-",
            TokenType.STAR_ASSIGN: "*",
            TokenType.SLASH_ASSIGN: "/",
        }
        for tok_type, op_symbol in compound_map.items():
            if self._match(tok_type):
                rhs = self._parse_expression()
                self._expect(
                    TokenType.SEMICOLON,
                    f"Expected ';' after compound assignment to '{var_name}'",
                )
                combined = BinaryOp(
                    line=id_tok.line,
                    column=id_tok.column,
                    op=op_symbol,
                    left=Identifier(line=id_tok.line, column=id_tok.column, name=var_name),
                    right=rhs,
                )
                return Assignment(
                    line=id_tok.line,
                    column=id_tok.column,
                    name=var_name,
                    value=combined,
                )

        cur = self._current()
        self.errors.append(
            SyntaxErrorDetail(
                message=f"Expected '=' after identifier '{var_name}' in assignment statement (found '{cur.value}')",
                line=cur.line,
                column=cur.column,
                found_token=str(cur.value),
            )
        )
        raise _ParseAbortError()

    def _parse_print_stmt(self) -> PrintStmt:
        print_tok = self._advance()
        self._expect(TokenType.LPAREN, "Expected '(' after 'print'")

        expressions: List[ASTNode] = []
        if not self._check(TokenType.RPAREN):
            expressions.append(self._parse_expression())
            while self._match(TokenType.COMMA):
                expressions.append(self._parse_expression())
        else:
            self.errors.append(
                SyntaxErrorDetail(
                    message="print() requires at least one argument expression",
                    line=print_tok.line,
                    column=print_tok.column,
                    found_token=")",
                )
            )
            raise _ParseAbortError()

        self._expect(TokenType.RPAREN, "Expected ')' after print arguments")
        self._expect(TokenType.SEMICOLON, "Expected ';' after print() statement")
        return PrintStmt(
            line=print_tok.line,
            column=print_tok.column,
            expressions=expressions,
        )

    def _parse_if_stmt(self) -> IfStmt:
        if_tok = self._advance()
        self._expect(TokenType.LPAREN, "Expected '(' after 'if'")
        condition = self._parse_expression()
        self._expect(TokenType.RPAREN, "Expected ')' after if condition")

        then_branch = self._parse_statement_or_block("if")
        else_branch: Optional[ASTNode] = None

        if self._match(TokenType.ELSE):
            if self._check(TokenType.IF):
                else_branch = self._parse_if_stmt()
            else:
                else_branch = self._parse_statement_or_block("else")

        return IfStmt(
            line=if_tok.line,
            column=if_tok.column,
            condition=condition,
            then_branch=then_branch,
            else_branch=else_branch,
        )

    def _parse_while_stmt(self) -> WhileStmt:
        while_tok = self._advance()
        self._expect(TokenType.LPAREN, "Expected '(' after 'while'")
        condition = self._parse_expression()
        self._expect(TokenType.RPAREN, "Expected ')' after while condition")
        body = self._parse_statement_or_block("while")
        return WhileStmt(
            line=while_tok.line,
            column=while_tok.column,
            condition=condition,
            body=body,
        )

    def _parse_statement_or_block(self, construct_name: str) -> Block:
        if self._check(TokenType.LBRACE):
            return self._parse_block()
        stmt = self._parse_statement()
        stmts = [stmt] if stmt is not None else []
        tok = self._current()
        return Block(line=tok.line, column=tok.column, statements=stmts)

    def _parse_block(self) -> Block:
        lbrace_tok = self._expect(TokenType.LBRACE, "Expected '{' to begin block")
        statements: List[ASTNode] = []
        while not self._check(TokenType.RBRACE) and not self._is_at_end():
            try:
                stmt = self._parse_statement()
                if stmt is not None:
                    statements.append(stmt)
            except _ParseAbortError:
                self._synchronize()
        self._expect(TokenType.RBRACE, "Expected '}' to close block")
        return Block(
            line=lbrace_tok.line,
            column=lbrace_tok.column,
            statements=statements,
        )

    # --- Expression Hierarchy (Recursive Descent by Operator Precedence) ---

    def _parse_expression(self) -> ASTNode:
        return self._parse_logical_or()

    def _parse_logical_or(self) -> ASTNode:
        expr = self._parse_logical_and()
        while True:
            op_tok = self._match(TokenType.OR)
            if not op_tok:
                break
            right = self._parse_logical_and()
            expr = BinaryOp(
                line=op_tok.line,
                column=op_tok.column,
                op="||",
                left=expr,
                right=right,
            )
        return expr

    def _parse_logical_and(self) -> ASTNode:
        expr = self._parse_equality()
        while True:
            op_tok = self._match(TokenType.AND)
            if not op_tok:
                break
            right = self._parse_equality()
            expr = BinaryOp(
                line=op_tok.line,
                column=op_tok.column,
                op="&&",
                left=expr,
                right=right,
            )
        return expr

    def _parse_equality(self) -> ASTNode:
        expr = self._parse_comparison()
        while True:
            op_tok = self._match(TokenType.EQ, TokenType.NEQ)
            if not op_tok:
                break
            right = self._parse_comparison()
            expr = BinaryOp(
                line=op_tok.line,
                column=op_tok.column,
                op=str(op_tok.value),
                left=expr,
                right=right,
            )
        return expr

    def _parse_comparison(self) -> ASTNode:
        expr = self._parse_additive()
        while True:
            op_tok = self._match(TokenType.LT, TokenType.LTE, TokenType.GT, TokenType.GTE)
            if not op_tok:
                break
            right = self._parse_additive()
            expr = BinaryOp(
                line=op_tok.line,
                column=op_tok.column,
                op=str(op_tok.value),
                left=expr,
                right=right,
            )
        return expr

    def _parse_additive(self) -> ASTNode:
        expr = self._parse_multiplicative()
        while True:
            op_tok = self._match(TokenType.PLUS, TokenType.MINUS)
            if not op_tok:
                break
            right = self._parse_multiplicative()
            expr = BinaryOp(
                line=op_tok.line,
                column=op_tok.column,
                op=str(op_tok.value),
                left=expr,
                right=right,
            )
        return expr

    def _parse_multiplicative(self) -> ASTNode:
        expr = self._parse_unary()
        while True:
            op_tok = self._match(TokenType.STAR, TokenType.SLASH, TokenType.PERCENT)
            if not op_tok:
                break
            right = self._parse_unary()
            expr = BinaryOp(
                line=op_tok.line,
                column=op_tok.column,
                op=str(op_tok.value),
                left=expr,
                right=right,
            )
        return expr

    def _parse_unary(self) -> ASTNode:
        op_tok = self._match(TokenType.MINUS, TokenType.PLUS, TokenType.NOT)
        if op_tok:
            operand = self._parse_unary()
            op_str = "!" if op_tok.type == TokenType.NOT else str(op_tok.value)
            if op_str == "+":
                return operand
            return UnaryOp(
                line=op_tok.line,
                column=op_tok.column,
                op=op_str,
                operand=operand,
            )
        return self._parse_primary()

    def _parse_primary(self) -> ASTNode:
        tok = self._current()

        if self._match(TokenType.INT_LITERAL):
            return Literal(line=tok.line, column=tok.column, value=tok.value, literal_type="int")

        if self._match(TokenType.FLOAT_LITERAL):
            return Literal(line=tok.line, column=tok.column, value=tok.value, literal_type="float")

        if self._match(TokenType.STRING_LITERAL):
            return Literal(line=tok.line, column=tok.column, value=tok.value, literal_type="string")

        if self._match(TokenType.TRUE, TokenType.FALSE):
            return Literal(line=tok.line, column=tok.column, value=bool(tok.value), literal_type="bool")

        if self._match(TokenType.IDENTIFIER):
            return Identifier(line=tok.line, column=tok.column, name=str(tok.value))

        if self._match(TokenType.LPAREN):
            expr = self._parse_expression()
            self._expect(TokenType.RPAREN, "Expected ')' after parenthesized expression")
            return expr

        self.errors.append(
            SyntaxErrorDetail(
                message=f"Expected expression (literal, identifier, or '(...)'), found '{tok.value}'",
                line=tok.line,
                column=tok.column,
                found_token=str(tok.value),
            )
        )
        raise _ParseAbortError()
